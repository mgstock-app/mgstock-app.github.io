assert.equal(porTurno.extraFeriado,2);
assert.equal(porTurno.computados,4,"Feriado 2 trabajados + 2 extra = 4 turnos");
const porHora=resumenPersona("hora",semanas,"2026-11-09",hasta,["2026-11-12"]);
assert.equal(porHora.horas,0);
assert.equal(porHora.horasFeriado,480);
assert.equal(porHora.computados,960,"8 horas trabajadas + 8 horas extra feriado = 16 horas");
assert.equal(formatoHoras(480),"8:00");
assert.equal(evaluarDia({tt_e:"19:00"}).errores.length,0,"Entrada sola se guarda entre semana");
assert.ok(evaluarDia({tt_e:"19:00"},true).errores.length>0,"Domingo 23:40 exige completar");
assert.ok(evaluarDia({tm_e:"19:00",tm_s:"15:00"}).errores.length>0,"No permitir inversión de mañana");
assert.ok(evaluarDia({tm_e:"08:00",tm_s:"12:00",tt_e:"11:00",tt_s:"14:00"}).errores.length>0,"Evitar superposición");
assert.equal(evaluarDia({tt_e:"19:00",tt_s:"00:00"}).horas,300,"Turno tarde cruza medianoche");
