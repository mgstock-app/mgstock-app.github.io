assert.equal(revisarSemana("2026-11-09",new Date("2026-11-16T02:30:00Z")),false);
assert.equal(revisarSemana("2026-11-09",new Date("2026-11-16T02:39:59Z")),false);
assert.equal(revisarSemana("2026-11-09",new Date("2026-11-16T02:40:00Z")),true);
assert.equal(revisarSemana("2026-11-09",new Date("2026-11-16T03:00:00Z")),true);
assert.equal(revisarSemana("2026-11-16",new Date("2026-11-16T03:00:00Z")),false);
