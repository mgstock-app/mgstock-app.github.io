-- GestLok Web Push: private-by-default data, opt-in only.
-- No existing stock, user, or supplier record is changed by this migration.
create table if not exists public.gestlok_push_settings(
  id smallint primary key check(id=1),
  public_key text not null,
  private_jwk jsonb not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.gestlok_push_devices(
  endpoint text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tenant_id uuid not null references gestlok_tenancy.tenants(id) on delete cascade,
  auth_key text not null,
  p256dh_key text not null,
  enabled boolean not null default true,
  registered_at timestamptz not null default now()
);
create index if not exists gestlok_push_devices_by_tenant on public.gestlok_push_devices(tenant_id);
create table if not exists public.gestlok_push_events(
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references gestlok_tenancy.tenants(id) on delete cascade,
  local_id text not null,
  event_key text not null unique,
  title text not null,
  body text not null,
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  attempts integer not null default 0
);
create index if not exists gestlok_push_events_pending on public.gestlok_push_events(created_at) where delivered_at is null;
create table if not exists public.gestlok_push_control(
  id smallint primary key check(id=1),
  cron_token_hash text not null
);
alter table public.gestlok_push_settings enable row level security;
alter table public.gestlok_push_devices enable row level security;
alter table public.gestlok_push_events enable row level security;
alter table public.gestlok_push_control enable row level security;
revoke all on public.gestlok_push_settings, public.gestlok_push_devices,
  public.gestlok_push_events, public.gestlok_push_control from public,anon,authenticated;
grant select,insert,update,delete on public.gestlok_push_settings, public.gestlok_push_devices,
  public.gestlok_push_events, public.gestlok_push_control to service_role;
grant usage,select on sequence public.gestlok_push_events_id_seq to service_role;

-- A database event is queued whenever an authorized person changes a relevant document.
-- No browser credentials or "push enabled" flag is assumed; delivery happens only to
-- devices that separately opted in.
create or replace function public.gestlok_enqueue_alert() returns trigger
language plpgsql security definer set search_path=''
as $$
declare
  loc text; kind text; label text; detail text; actor text; display_actor text;
  dedupe text; old_no_stock boolean := false; new_no_stock boolean := false;
begin
  if new.tenant_id is null or strpos(new.col,'/')=0 then return new; end if;
  if tg_op='UPDATE' and old.data is not distinct from new.data then return new; end if;
  loc:=split_part(new.col,'/',1);
  kind:=split_part(new.col,'/',2);
  if kind not in ('conteos','proveedores','chat','productos','vencimientos') then return new; end if;
  if not exists(select 1 from public.docs l where l.tenant_id=new.tenant_id and l.col='locales' and l.id=loc) then return new; end if;
  select coalesce(l.data->>'nombre',loc) into label from public.docs l
  where l.tenant_id=new.tenant_id and l.col='locales' and l.id=loc;
  actor:=lower(coalesce(new.updated_by,''));
  select coalesce(nullif(x.data->>'nombre',''),split_part(actor,'@',1),'Un integrante')
  into display_actor
  from public.docs x where x.tenant_id=new.tenant_id
    and x.col='equipo' and lower(x.data->>'email')=actor limit 1;
  display_actor:=left(coalesce(nullif(display_actor,''),'Un integrante'),70);
  if kind='conteos' and tg_op='INSERT' then
    if coalesce(new.data->>'hoja',new.data->>'nombreHoja','') ilike '%caja%' then
      label:='Stock Cajas realizado';
    else label:='Conteo realizado';
    end if;
    detail:=display_actor||' guardó un conteo en '||coalesce((select l.data->>'nombre' from public.docs l where l.col='locales' and l.id=loc and l.tenant_id=new.tenant_id),loc);
  elsif kind='proveedores' then
    detail:=display_actor||' actualizó información de proveedores.';
    label:='Proveedores · '||label;
  elsif kind='chat' and tg_op='INSERT' then
    detail:='Hay un mensaje nuevo en el chat del local.';
    label:='Chat interno · '||label;
  elsif kind='vencimientos' then
    detail:=coalesce(new.data->>'nombre','Servicio')||' · Vence '||coalesce(new.data->>'fechaVencimiento','');
    label:='Vencimientos · '||label;
  elsif kind='productos' then
    new_no_stock:=(new.data->>'sinStock'='true') or
      (coalesce(new.data->>'stock','') ~ '^[0-9]+([.][0-9]+)?$'
       and (new.data->>'stock')::numeric=0);
    if tg_op='UPDATE' then
      old_no_stock:=(old.data->>'sinStock'='true') or
        (coalesce(old.data->>'stock','') ~ '^[0-9]+([.][0-9]+)?$'
         and (old.data->>'stock')::numeric=0);
    end if;
    if not new_no_stock or old_no_stock then return new; end if;
    detail:=coalesce(new.data->>'nombre','Un producto')||' quedó sin stock.';
    label:='Stock · '||label;
  else return new;
  end if;
  dedupe:=new.tenant_id::text||':'||new.col||':'||new.id||':'||extract(epoch from new.updated_at)::text||':'||txid_current()::text;
  insert into public.gestlok_push_events(tenant_id,local_id,event_key,title,body)
  values(new.tenant_id,loc,dedupe,left(label,100),left(detail,240))
  on conflict(event_key) do nothing;
  -- Historial visual dentro de la sucursal; evita guardar textos privados del chat.
  insert into public.docs(col,id,data,tenant_id,updated_by)
  values(loc||'/avisos',gen_random_uuid()::text,
    jsonb_build_object('titulo',left(label,100),'detalle',left(detail,240),'fecha',(extract(epoch from now())*1000)::bigint),
    new.tenant_id,new.updated_by);
  return new;
end $$;
revoke all on function public.gestlok_enqueue_alert() from public,anon,authenticated;
drop trigger if exists gestlok_notify_docs_changes on public.docs;
create trigger gestlok_notify_docs_changes
after insert or update of data on public.docs
for each row execute function public.gestlok_enqueue_alert();

-- Exactly one daily digest per company and location; at 23:15 Argentine time
-- the scheduler calls this function and then the push dispatcher.
create or replace function public.gestlok_queue_daily_digest() returns integer
language plpgsql security definer set search_path=''
as $$
declare
  l record; the_day date := (now() at time zone 'America/Argentina/Buenos_Aires')::date;
  counted integer; no_stock integer; due_soon integer; done integer := 0;
  s text;
begin
  for l in select d.id,d.tenant_id,coalesce(d.data->>'nombre',d.id) as local_name
           from public.docs d where d.col='locales' loop
    select count(*) into counted from public.docs d
     where d.tenant_id=l.tenant_id and d.col=l.id||'/conteos'
     and case when coalesce(d.data->>'fecha','') ~ '^[0-9]{12,13}$'
         then (to_timestamp((d.data->>'fecha')::numeric/1000) at time zone 'America/Argentina/Buenos_Aires')::date
         else null end = the_day;
    select count(*) into no_stock from public.docs d
     where d.tenant_id=l.tenant_id and d.col=l.id||'/productos'
      and ((d.data->>'sinStock')='true' or
        (coalesce(d.data->>'stock','') ~ '^[0-9]+([.][0-9]+)?$' and (d.data->>'stock')::numeric=0));
    select count(*) into due_soon from public.docs d
     where d.tenant_id=l.tenant_id and d.col=l.id||'/vencimientos'
      and coalesce(d.data->>'activo','true') <> 'false'
      and coalesce(d.data->>'fechaVencimiento','') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
      and d.data->>'fechaVencimiento' <= to_char(the_day+5,'YYYY-MM-DD');
    s:=case when counted=0 then 'No se hizo el conteo de hoy' else counted::text||' conteos registrados' end
       ||' · '||no_stock::text||' productos sin stock · '||due_soon::text||' servicios próximos/vencidos';
    insert into public.gestlok_push_events(tenant_id,local_id,event_key,title,body)
      values(l.tenant_id,l.id,'cierre:'||l.tenant_id::text||':'||l.id||':'||the_day::text,
        'Cierre 23:15 · '||left(l.local_name,70),left(s,240))
    on conflict(event_key) do nothing;
    done:=done+1;
  end loop;
  return done;
end $$;
revoke all on function public.gestlok_queue_daily_digest() from public,anon,authenticated;
